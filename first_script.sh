#!/bin/bash

echo "🚀 Начинаем системный чек-ап и обслуживание..."
echo "Привет, $(whoami)! Текущий хост: $(hostname)"
echo "Дата и время: $(date)"
echo "-------------------------------------------"
echo "📦 Обновляю списки пакетов..."
sudo apt-get update -y > /dev/null 2>&1
echo "✅ Репозитории обновлены."
echo "🧹 Чищу систему от мусора..."
sudo apt-get autoremove -y > /dev/null 2>&1
sudo apt-get clean
echo "✅ Система чиста."
echo "-------------------------------------------"
echo "🎉 Обслуживание завершено! Инфраструктура готова к бою."
